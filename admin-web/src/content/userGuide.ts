export function matchesGuideQuestion(question: GuideQuestion, query: string) {
  return `${question.question} ${question.answer}`.toLocaleLowerCase().includes(query.trim().toLocaleLowerCase())
}

export function searchGuideTopics(query: string) {
  const keyword = query.trim().toLocaleLowerCase()
  if (!keyword) return guideTopics
  return guideTopics.filter((topic) => [
    topic.title, topic.introduction, topic.note ?? '', ...topic.tips,
    ...topic.steps.flatMap((step) => [step.title, step.description]),
    ...topic.questions.flatMap((question) => [question.question, question.answer]),
  ].join(' ').toLocaleLowerCase().includes(keyword))
}
